"""Convert the Sigma rules into Splunk SPL and Google SecOps queries.

Output (generated, never edited by hand):
    converted/splunk/<rule>.spl              one SPL search per rule
    converted/splunk/savedsearches.conf      all rules as deployable Splunk saved searches
    converted/secops/udm_search/<rule>.txt   UDM search queries (SecOps investigation)
    converted/secops/yara_l/<rule>.yaral     YARA-L 2.0 detection rules
    converted/CONVERSION_REPORT.md           per-rule status for every target

Splunk conversion must succeed for every rule; a failure fails the build.
The SecOps backend (pySigma-backend-secops, YARA-L output marked beta upstream) cannot
map every Windows field to Google's UDM schema. Those rules are reported as
unsupported with the reason, instead of guessing at a UDM field that might silently
never match.

Usage:
    uv run python scripts/convert_rules.py          # regenerate converted/
    uv run python scripts/convert_rules.py --check  # fail if converted/ is out of date
"""

import argparse
import copy
import re
import shutil
import sys
import tempfile
from dataclasses import dataclass
from pathlib import Path

from sigma.backends.secops import SecOpsBackend
from sigma.backends.splunk import SplunkBackend
from sigma.collection import SigmaCollection
from sigma.plugins import InstalledSigmaPlugins
from sigma.rule import SigmaRule

REPO_ROOT = Path(__file__).resolve().parent.parent
RULES_DIR = REPO_ROOT / "rules" / "sigma"
OUTPUT_DIR = REPO_ROOT / "converted"
# This repo's GCP Cloud Audit Log field mappings (installed pipelines cover Windows only).
GCP_SPLUNK = str(REPO_ROOT / "pipelines" / "gcp_audit_splunk.yml")
GCP_SECOPS = str(REPO_ROOT / "pipelines" / "gcp_audit_secops.yml")

HEADER = "Generated by scripts/convert_rules.py from {source}. Do not edit by hand."


@dataclass
class Target:
    """One conversion target: backend, pipelines, output format and file layout."""

    key: str
    label: str
    backend_class: type
    pipelines: list[str]
    output_format: str
    subdir: str
    extension: str
    comment: str  # comment prefix for the generated-file header
    required: bool  # if True, any conversion failure fails the build


TARGETS = [
    Target("splunk", "Splunk SPL", SplunkBackend, [GCP_SPLUNK, "sysmon", "splunk_windows"],
           "default", "splunk", ".spl", "```", True),
    Target("secops_udm", "SecOps UDM search", SecOpsBackend, [GCP_SECOPS, "secops_udm"],
           "default", "secops/udm_search", ".txt", "//", False),
    Target("secops_yaral", "SecOps YARA-L 2.0 (beta)", SecOpsBackend, [GCP_SECOPS, "secops_udm"],
           "yara_l", "secops/yara_l", ".yaral", "//", False),
]  # fmt: skip


def yaral_safe(rule: SigmaRule) -> SigmaRule:
    """Return a copy of the rule whose text fields are safe inside YARA-L meta strings.

    The SecOps backend copies description and false positives into `meta:` verbatim.
    Multi-line text and double quotes break YARA-L string syntax, so collapse
    whitespace and swap double quotes for single quotes. Detection logic is untouched.
    """
    safe = copy.deepcopy(rule)

    def clean(text: str) -> str:
        return " ".join(text.split()).replace('"', "'")

    safe.title = clean(safe.title)
    if safe.description:
        safe.description = clean(safe.description)
    safe.falsepositives = [clean(fp) for fp in safe.falsepositives]
    return safe


def fix_yaral_rule_name(text: str) -> str:
    """YARA-L rule names allow only letters, digits and underscores.

    The backend derives the name from the title, so "Scrobj.dll (Squiblydoo)" produces
    an invalid name. Replace any other character with "_". Only the name changes.
    """
    header, _, rest = text.partition("{")
    keyword, _, name = header.strip().partition(" ")
    clean = re.sub(r"[^A-Za-z0-9]+", "_", name).strip("_")
    return f"{keyword} {clean} {{{rest}"


def top_level_operators(expression: str) -> set[str]:
    """AND/OR operators that appear outside parentheses, "strings" and /regexes/.

    In YARA-L and UDM search, AND binds tighter than OR. If both appear at the same
    nesting level without parentheses, the query almost certainly does not mean what
    the Sigma rule meant, so the conversion is flagged instead of trusted.
    """
    operators: set[str] = set()
    depth, i = 0, 0
    while i < len(expression):
        char = expression[i]
        if char in '"/':  # skip a string or regex literal, honouring backslash escapes
            i += 1
            while i < len(expression) and expression[i] != char:
                i += 2 if expression[i] == "\\" else 1
        elif char == "(":
            depth += 1
        elif char == ")":
            depth -= 1
        elif depth == 0:
            operators |= {op.strip() for op in (" AND ", " OR ") if expression.startswith(op, i)}
        i += 1
    return operators


def precedence_problem(target: Target, body: str) -> bool:
    if target.output_format == "yara_l":
        # Each line of the events: section is one expression.
        events = body.split("events:")[1].split("conditions:")[0]
        expressions = events.strip().splitlines()
    else:
        expressions = [body]
    return any(top_level_operators(e) == {"AND", "OR"} for e in expressions)


NEGATED = re.compile(r"\bnot\s+(?:(1|all)\s+of\s+)?([\w*]+)")


def negated_multi_item_filters(rule: SigmaRule) -> list[str]:
    """Names of negated detections that hold two or more conditions.

    pySigma-backend-secops 1.0.0 drops the NOT from "not (A and B)" and emits
    "A and B", which compiles but inverts the rule: it then alerts only on the
    activity the filter was meant to exclude. A single negated condition converts
    correctly (to !=), so only multi-condition filters are affected.
    """
    names = []
    for condition in rule.detection.condition:
        for _, pattern in NEGATED.findall(condition):
            regex = re.compile("^" + re.escape(pattern).replace(r"\*", ".*") + "$")
            for name, detection in rule.detection.detections.items():
                if regex.match(name) and len(detection.detection_items) > 1:
                    names.append(name)
    return sorted(set(names))


def short_error(error: Exception) -> str:
    """First line of the error without the long '(while applying ... rule <path>)' suffix."""
    message = str(error).splitlines()[0]
    return message.split(" (while ")[0]


def comment_header(target: Target, source: str) -> str:
    text = HEADER.format(source=source)
    if target.comment == "```":  # SPL comments are wrapped in triple backticks
        return f"``` {text} ```\n"
    return f"// {text}\n"


def convert_all(out_dir: Path) -> dict[str, dict[str, str]]:
    """Write every target's output under out_dir. Returns {rule: {target key: status}}."""
    resolver = InstalledSigmaPlugins.autodiscover().get_pipeline_resolver()
    rule_paths = sorted(RULES_DIR.rglob("*.yml"))
    status: dict[str, dict[str, str]] = {p.stem: {} for p in rule_paths}

    for target in TARGETS:
        target_dir = out_dir / target.subdir
        target_dir.mkdir(parents=True, exist_ok=True)
        for path in rule_paths:
            rule = SigmaRule.from_yaml(path.read_text("utf-8"))
            if target.backend_class is SecOpsBackend:
                rule = yaral_safe(rule)
            # A fresh backend per rule: pipelines keep per-conversion state.
            backend = target.backend_class(resolver.resolve(target.pipelines))
            source = path.relative_to(REPO_ROOT).as_posix()
            try:
                queries = backend.convert(SigmaCollection([rule]), target.output_format)
            except Exception as error:  # backend raises many error types; report them all
                status[path.stem][target.key] = f"unsupported: {short_error(error)}"
                continue
            body = "\n".join(str(q).strip() for q in queries)
            if target.output_format == "yara_l":
                body = fix_yaral_rule_name(body)
            header = comment_header(target, source)
            dropped_not = negated_multi_item_filters(rule)
            if target.backend_class is SecOpsBackend and dropped_not:
                status[path.stem][target.key] = (
                    "not deployable: backend drops NOT from multi-condition filters "
                    f"({', '.join(dropped_not)}), so the rule alerts on what it should exclude"
                )
                header += "// DO NOT DEPLOY: the backend dropped a NOT; logic is inverted.\n"
            elif target.backend_class is SecOpsBackend and precedence_problem(target, body):
                # Keep the file so the problem is visible, but make it impossible to miss.
                status[path.stem][target.key] = (
                    "not deployable: backend output mixes AND/OR without parentheses, "
                    "which changes the rule's logic"
                )
                header += "// DO NOT DEPLOY: AND/OR precedence differs from the Sigma rule.\n"
            else:
                status[path.stem][target.key] = "ok"
            (target_dir / f"{path.stem}{target.extension}").write_text(
                header + body + "\n", encoding="utf-8", newline="\n"
            )

    # Splunk savedsearches.conf with every rule, ready to drop into a Splunk app.
    splunk = next(t for t in TARGETS if t.key == "splunk")
    backend = SplunkBackend(resolver.resolve(splunk.pipelines))
    collection = SigmaCollection([SigmaRule.from_yaml(p.read_text("utf-8")) for p in rule_paths])
    conf = backend.convert(collection, "savedsearches")
    conf_text = conf if isinstance(conf, str) else "\n".join(map(str, conf))
    (out_dir / "splunk" / "savedsearches.conf").write_text(
        f"# {HEADER.format(source='rules/sigma/')}\n{conf_text.strip()}\n",
        encoding="utf-8",
        newline="\n",
    )

    write_report(out_dir, status)
    return status


def write_report(out_dir: Path, status: dict[str, dict[str, str]]) -> None:
    lines = [
        "# Conversion report",
        "",
        f"_{HEADER.format(source='rules/sigma/')}_",
        "",
        "| Rule | " + " | ".join(t.label for t in TARGETS) + " |",
        "|---" * (len(TARGETS) + 1) + "|",
    ]
    icons = {"ok": "✅", "not deployable": "⚠️", "unsupported": "❌"}
    for rule, results in status.items():
        cells = [icons[results[t.key].split(":")[0]] for t in TARGETS]
        lines.append(f"| {rule} | " + " | ".join(cells) + " |")

    lines += [
        "",
        "✅ converted and passed checks · ⚠️ generated but logically wrong (do not deploy) · "
        "❌ backend cannot convert",
        "",
        "## Problems",
        "",
    ]
    problems = [
        (rule, t.label, results[t.key])
        for rule, results in status.items()
        for t in TARGETS
        if results[t.key] != "ok"
    ]
    if not problems:
        lines.append("None.")
    for rule, label, message in problems:
        lines.append(f"- **{rule}** ({label}): {message}")
    lines += [
        "",
        "SecOps output is generated by pySigma-backend-secops (YARA-L format is beta upstream)",
        "and has not been executed against a Google SecOps tenant. See docs/conversion.md.",
        "",
    ]
    (out_dir / "CONVERSION_REPORT.md").write_text("\n".join(lines), encoding="utf-8", newline="\n")


def tree_bytes(root: Path) -> dict[str, bytes]:
    return {p.relative_to(root).as_posix(): p.read_bytes() for p in root.rglob("*") if p.is_file()}


def main() -> int:
    parser = argparse.ArgumentParser(description="Convert Sigma rules to Splunk and SecOps.")
    parser.add_argument("--check", action="store_true", help="fail if converted/ is stale")
    args = parser.parse_args()

    with tempfile.TemporaryDirectory() as tmp:
        fresh = Path(tmp) / "converted"
        status = convert_all(fresh)

        if args.check:
            stale = tree_bytes(fresh) != tree_bytes(OUTPUT_DIR) if OUTPUT_DIR.exists() else True
            if stale:
                print("converted/ is out of date. Run: uv run python scripts/convert_rules.py")
        else:
            shutil.rmtree(OUTPUT_DIR, ignore_errors=True)
            shutil.copytree(fresh, OUTPUT_DIR)
            stale = False

    for target in TARGETS:
        ok = sum(1 for r in status.values() if r[target.key] == "ok")
        print(f"{target.label:28} {ok}/{len(status)} rules converted")

    required_failures = [
        f"{rule} ({t.label}): {results[t.key]}"
        for rule, results in status.items()
        for t in TARGETS
        if t.required and results[t.key] != "ok"
    ]
    for failure in required_failures:
        print(f"[REQUIRED TARGET FAILED] {failure}")
    return 1 if required_failures or stale else 0


if __name__ == "__main__":
    sys.exit(main())
