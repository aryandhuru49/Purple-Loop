"""Generate a MITRE ATT&CK Navigator layer and a coverage table from rule tags.

Reads ATT&CK technique IDs from:
  * Sigma rules (rules/sigma)       tags like attack.t1003.001; these are TESTED
  * YARA-L rules (rules/yara_l)     meta mitre_attack_id; these are NOT executed
  * YARA rules (rules/yara)         meta mitre_attack_id; TESTED (tests/test_yara_rules.py)

Writes (generated, checked in CI):
  coverage/attack_navigator_layer.json   open at https://mitre-attack.github.io/attack-navigator/
                                         (Open Existing Layer -> Upload from local)
  coverage/COVERAGE.md                   the same coverage as a readable table

Score = number of rules covering the technique. Each technique's comment lists the
rules and whether they are tested, so the layer is honest about what is verified.

Usage:
    uv run python scripts/generate_coverage.py          # regenerate coverage/
    uv run python scripts/generate_coverage.py --check  # fail if coverage/ is stale
"""

import argparse
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

import yaml
import yara
from sigma.data.mitre_attack import (
    mitre_attack_techniques,
    mitre_attack_techniques_tactics_mapping,
    mitre_attack_version,
)

REPO_ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = REPO_ROOT / "coverage"

# Versions verified against mitre-attack/attack-navigator (release v5.3.2, layer spec v4.5).
NAVIGATOR_VERSION = "5.3.2"
LAYER_FORMAT_VERSION = "4.5"

TECHNIQUE_TAG = re.compile(r"^attack\.(t\d{4}(?:\.\d{3})?)$")


def collect() -> dict[str, list[dict]]:
    """Return {technique ID: [{rule, source, tested}]}."""
    coverage: dict[str, list[dict]] = defaultdict(list)

    for path in sorted((REPO_ROOT / "rules" / "sigma").rglob("*.yml")):
        rule = yaml.safe_load(path.read_text("utf-8"))
        for tag in rule.get("tags", []):
            if match := TECHNIQUE_TAG.match(tag):
                coverage[match.group(1).upper()].append(
                    {"rule": rule["title"], "source": "Sigma", "tested": True}
                )

    for path in sorted((REPO_ROOT / "rules" / "yara_l").glob("*.yaral")):
        text = path.read_text("utf-8")
        ids = re.search(r'mitre_attack_id\s*=\s*"([^"]+)"', text).group(1)
        name = re.search(r"^rule\s+(\w+)", text, re.MULTILINE).group(1)
        for technique in (t.strip().upper() for t in ids.split(",")):
            coverage[technique].append({"rule": name, "source": "YARA-L", "tested": False})

    for path in sorted((REPO_ROOT / "rules" / "yara").glob("*.yar")):
        for rule in yara.compile(filepath=str(path)):
            for technique in (t.strip().upper() for t in rule.meta["mitre_attack_id"].split(",")):
                coverage[technique].append(
                    {"rule": rule.identifier, "source": "YARA", "tested": True}
                )

    unknown = [t for t in coverage if t not in mitre_attack_techniques]
    if unknown:
        sys.exit(f"Techniques not in ATT&CK {mitre_attack_version}: {unknown}")
    return dict(sorted(coverage.items()))


def build_layer(coverage: dict[str, list[dict]]) -> dict:
    techniques = []
    for technique_id, rules in coverage.items():
        tested = sum(r["tested"] for r in rules)
        comment = "; ".join(
            f"{r['source']}: {r['rule']} ({'tested' if r['tested'] else 'not executed'})"
            for r in rules
        )
        # One entry per tactic the technique belongs to, so it shows in every column.
        for tactic in mitre_attack_techniques_tactics_mapping.get(technique_id, []):
            techniques.append(
                {
                    "techniqueID": technique_id,
                    "tactic": tactic,
                    "score": len(rules),
                    "comment": comment,
                    "enabled": True,
                    "showSubtechniques": True,
                    "metadata": [
                        {"name": "rules", "value": str(len(rules))},
                        {"name": "tested rules", "value": str(tested)},
                    ],
                }
            )

    return {
        "name": "Purple Loop detection coverage",
        "versions": {
            "attack": str(mitre_attack_version).split(".")[0],
            "navigator": NAVIGATOR_VERSION,
            "layer": LAYER_FORMAT_VERSION,
        },
        "domain": "enterprise-attack",
        "description": (
            "Techniques covered by Purple Loop rules. Score = number of rules. "
            "Sigma and YARA rules are tested in CI; YARA-L rules are reviewed but not "
            "executed. Generated by scripts/generate_coverage.py."
        ),
        "filters": {"platforms": ["Windows"]},
        "sorting": 3,  # sort by score, descending
        "layout": {"layout": "side", "showName": True, "showID": True},
        "hideDisabled": False,
        "techniques": techniques,
        "gradient": {"colors": ["#d6c8f0ff", "#6a3fb5ff"], "minValue": 0, "maxValue": 3},
        "legendItems": [
            {"label": "Covered by 1 rule", "color": "#d6c8f0ff"},
            {"label": "Covered by 3+ rules", "color": "#6a3fb5ff"},
        ],
        "showTacticRowBackground": True,
        "tacticRowBackground": "#2b1b4a",
        "selectTechniquesAcrossTactics": True,
        "selectSubtechniquesWithParent": False,
    }


def build_markdown(coverage: dict[str, list[dict]]) -> str:
    lines = [
        "# ATT&CK coverage",
        "",
        f"_Generated by scripts/generate_coverage.py against ATT&CK v{mitre_attack_version}. "
        "Do not edit by hand._",
        "",
        "| Technique | Name | Tactics | Sigma (tested) | YARA (tested) | YARA-L (not executed) |",
        "|---|---|---|---|---|---|",
    ]
    for technique_id, rules in coverage.items():
        tactics = ", ".join(mitre_attack_techniques_tactics_mapping.get(technique_id, []))
        sigma = "<br>".join(r["rule"] for r in rules if r["source"] == "Sigma") or "-"
        yara_rules = "<br>".join(r["rule"] for r in rules if r["source"] == "YARA") or "-"
        yaral = "<br>".join(r["rule"] for r in rules if r["source"] == "YARA-L") or "-"
        url = f"https://attack.mitre.org/techniques/{technique_id.replace('.', '/')}/"
        lines.append(
            f"| [{technique_id}]({url}) | {mitre_attack_techniques[technique_id]} | "
            f"{tactics} | {sigma} | {yara_rules} | {yaral} |"
        )
    lines += ["", f"{len(coverage)} techniques covered.", ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate ATT&CK coverage outputs.")
    parser.add_argument("--check", action="store_true", help="fail if coverage/ is stale")
    args = parser.parse_args()

    coverage = collect()
    outputs = {
        OUT_DIR / "attack_navigator_layer.json": json.dumps(build_layer(coverage), indent=2) + "\n",
        OUT_DIR / "COVERAGE.md": build_markdown(coverage),
    }
    stale = False
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text("utf-8") != content:
                print(f"[STALE] {path.relative_to(REPO_ROOT)}")
                stale = True
        else:
            path.parent.mkdir(exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    print(f"{len(coverage)} techniques covered (ATT&CK v{mitre_attack_version}).")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
